"""Build the /pages/faqs theme files from faq_content.py.

Outputs (under theme/):
  templates/page.faq.json     - banner, sticky jump links, one Custom FAQs section per category
  sections/faq-schema.liquid  - single FAQPage JSON-LD block, generated from the same text

Run: python3 build.py
"""
import html
import json
import re
from pathlib import Path

import faq_content as c

HERE = Path(__file__).parent
THEME = HERE / "theme"
LIVE_TEMPLATE = HERE / "live-snapshot" / "page.faq.json"

TEMPLATE_HEADER = """/*
 * ------------------------------------------------------------
 * IMPORTANT: The contents of this file are auto-generated.
 *
 * This file may be updated by the Shopify admin theme editor
 * or related systems. Please exercise caution as any changes
 * made to this file may be overwritten.
 * ------------------------------------------------------------
 */
"""

BG_COLORS = ["#e8e8e8", "#fafafa"]


def load_live_template():
    text = LIVE_TEMPLATE.read_text()
    return json.loads(text[text.index("{"):])


def ingredients_table():
    rows = "".join(
        f"<tr><td>{html.escape(n)}</td><td>{html.escape(f)}</td><td>{html.escape(d)}</td><td>{html.escape(p)}</td></tr>"
        for n, f, d, p in c.INGREDIENTS
    )
    return (
        "<table><thead><tr><th scope=\"col\">Ingredient</th><th scope=\"col\">Form</th>"
        "<th scope=\"col\">Per 2 capsules</th><th scope=\"col\">% NRV</th></tr></thead>"
        f"<tbody>{rows}</tbody></table><p>{html.escape(c.INGREDIENTS_FOOTNOTE)}</p>"
    )


def ingredients_list_html():
    """Schema-safe version of the table (Google allows lists, not tables, in answers)."""
    items = []
    for n, f, d, p in c.INGREDIENTS:
        form = "" if f == "—" else f" ({f})"
        nrv = "" if p == "†" else f", {p} NRV"
        items.append(f"<li>{html.escape(n + form)}: {html.escape(d)}{html.escape(nrv)}</li>")
    return "<ul>" + "".join(items) + "</ul>"


def jump_nav_liquid():
    links = "".join(
        f'<a href="#{anchor}">{html.escape(label)}</a>' for anchor, label, _, _ in c.CATEGORIES
    )
    return (
        "<style>"
        ".shopify-section:has(.faq-jump-nav){position:sticky;top:0;z-index:3;}"
        ".faq-jump-nav{background:#fafafa;border-bottom:1px solid rgba(var(--dark-rgb),0.15);}"
        ".faq-jump-nav__inner{display:flex;gap:8px;overflow-x:auto;-webkit-overflow-scrolling:touch;"
        "scrollbar-width:none;padding-top:12px;padding-bottom:12px;}"
        ".faq-jump-nav__inner::-webkit-scrollbar{display:none;}"
        ".faq-jump-nav a{flex:0 0 auto;white-space:nowrap;padding:8px 14px;border:1px solid rgba(var(--dark-rgb),0.3);"
        "border-radius:999px;font-size:14px;line-height:1;color:rgb(var(--dark-rgb));text-decoration:none;}"
        ".faq-jump-nav a:hover,.faq-jump-nav a:focus-visible{background:rgb(var(--dark-rgb));color:#fafafa;}"
        "</style>"
        f'<nav class="faq-jump-nav" aria-label="FAQ categories"><div class="faq-jump-nav__inner page-width">{links}</div></nav>'
    )


def faq_schema():
    entities = []
    for _, _, _, questions in c.CATEGORIES:
        for q, a in questions:
            answer = a
            if q == "What ingredients are in MUTO?":
                answer = a + ingredients_list_html() + f"<p>{html.escape(c.INGREDIENTS_FOOTNOTE)}</p>"
            # Make in-page anchors absolute so the answer stands alone when quoted.
            answer = re.sub(r'href="#', 'href="https://muto.co/pages/faqs#', answer)
            answer = re.sub(r'href="/', 'href="https://muto.co/', answer)
            entities.append({
                "@type": "Question",
                "name": q,
                "acceptedAnswer": {"@type": "Answer", "text": answer},
            })
    data = {
        "@context": "https://schema.org",
        "@type": "FAQPage",
        "url": "https://muto.co/pages/faqs",
        "mainEntity": entities,
    }
    body = json.dumps(data, ensure_ascii=False, indent=2).replace("</", "<\\/")
    return (
        "{% comment %}\n"
        "  FAQPage JSON-LD for /pages/faqs. Generated by shopify/faq/build.py from the same\n"
        "  text as the visible accordions. If you edit an answer in the theme editor, update\n"
        "  it here too so the wording stays identical.\n"
        "{% endcomment %}\n"
        '<script type="application/ld+json">\n' + body + "\n</script>\n\n"
        "{% schema %}\n"
        '{\n  "name": "FAQ schema (JSON-LD)",\n  "tag": "div",\n  "settings": []\n}\n'
        "{% endschema %}\n"
    )


def build_template():
    live = load_live_template()
    sections = {"main": live["sections"]["main"]}

    banner = live["sections"]["image_banner_A73Ley"]
    banner["blocks"]["text_AXtcf3"]["settings"]["text"] = c.INTRO

    sections["faq_byline"] = {
        "type": "custom-liquid",
        "name": "FAQ byline",
        "settings": {
            "custom_liquid": (
                "<p class=\"faq-byline page-width\" style=\"margin:0;font-size:13px;line-height:1.4;"
                f"color:rgba(var(--dark-rgb),0.75);\">{c.BYLINE}</p>"
            ),
            "color_scheme": "scheme-1",
            "padding_top": 16,
            "padding_bottom": 16,
        },
    }
    sections["image_banner_A73Ley"] = banner

    sections["faq_jump_nav"] = {
        "type": "custom-liquid",
        "name": "FAQ jump links",
        "settings": {
            "custom_liquid": jump_nav_liquid(),
            "color_scheme": "scheme-1",
            "padding_top": 0,
            "padding_bottom": 0,
        },
    }

    order = ["main", "image_banner_A73Ley", "faq_byline", "faq_jump_nav"]
    q_index = 0
    for i, (anchor, _, heading, questions) in enumerate(c.CATEGORIES):
        blocks, block_order = {}, []
        for q, a in questions:
            q_index += 1
            bid = f"faq_q{q_index:02d}"
            settings = {"heading": q, "content": a}
            if q == "What ingredients are in MUTO?":
                settings["content_html"] = ingredients_table()
            blocks[bid] = {"type": "faq", "settings": settings}
            block_order.append(bid)
        sid = f"faqs_{anchor.replace('-', '_')}"
        is_last = i == len(c.CATEGORIES) - 1
        sections[sid] = {
            "type": "custom-faqs",
            "blocks": blocks,
            "block_order": block_order,
            "settings": {
                "bg_color": BG_COLORS[i % 2],
                "padding_top": 60,
                "padding_bottom": 60,
                "custom_class": "",
                "anchor_id": anchor,
                "heading": f"<p>{html.escape(heading)}</p>",
                "bottom_text": c.CLOSING_HTML if is_last else "",
            },
        }
        order.append(sid)

    sections["faq_schema"] = {"type": "faq-schema", "settings": {}}
    order.append("faq_schema")

    template = {"sections": sections, "order": order}
    return TEMPLATE_HEADER + json.dumps(template, ensure_ascii=False, indent=2) + "\n", q_index


def main():
    (THEME / "templates").mkdir(parents=True, exist_ok=True)
    (THEME / "sections").mkdir(parents=True, exist_ok=True)
    template, count = build_template()
    (THEME / "templates" / "page.faq.json").write_text(template)
    (THEME / "sections" / "faq-schema.liquid").write_text(faq_schema())
    print(f"{len(c.CATEGORIES)} categories, {count} questions")


if __name__ == "__main__":
    main()
